function lines = c2837x_block_format_generation_result(result, project, legacyFileRisks)
%C2837X_BLOCK_FORMAT_GENERATION_RESULT Format a generation transaction result.

if isempty(fieldnames(result))
    lines = {'Generate blocked: valid Preview required.'};
    return;
end

lines = {sprintf('Status: %s', result.status), ...
    sprintf('Phase: %s', result.phase), ...
    sprintf('DSP Output Root: %s', result.dsp_root), ...
    sprintf('S-Function Output Root: %s', result.sfun_root), ...
    sprintf('Created Count: %u', result.created_count), ...
    sprintf('Replaced Count: %u', result.replaced_count), ...
    sprintf('Skipped Count: %u', result.skipped_count), ...
    sprintf('Kept Count: %u', result.kept_count), ...
    sprintf('Failed Count: %u', result.failed_count), ...
    sprintf('Not Attempted Count: %u', result.not_attempted_count), ...
    sprintf('Created Directories: %u', numel(result.created_directories)), ...
    sprintf('Temporary Files Remaining: %u', ...
    numel(result.temporary_files_remaining))};

for index = 1:numel(project.instances)
    name = project.instances(index).internal_name;
    directory = fullfile(result.sfun_root, name);
    lines = [lines, {sprintf('S-Function Instance: %s', name), ...
        sprintf('S-Function Directory: %s', directory), ...
        sprintf('Build Script: %s', fullfile(directory, ...
        ['build_' name '_sfun.m'])), ...
        sprintf('Expected MEX: %s', fullfile(directory, ...
        [name '_sfun.' mexext]))}]; %#ok<AGROW>
end
lines = [lines, {'App does not build MEX files automatically.', ...
    'Re-run the instance build script after changing generated source.', ...
    'Use Simulink Normal mode.', ...
    'Each instance directory must be discoverable by MATLAB.'}];

for index = 1:numel(result.files)
    file = result.files(index);
    label = upper(strrep(file.outcome, '_', ' '));
    line = sprintf('[%s] %s', label, file.target_path);
    if strcmp(file.outcome, 'failed')
        line = sprintf('%s - %s: %s', line, file.code, file.message);
    end
    lines{end + 1} = line; %#ok<AGROW>
end
for index = 1:numel(result.created_directories)
    lines{end + 1} = sprintf('[CREATED DIRECTORY] %s', ...
        result.created_directories{index}); %#ok<AGROW>
end
for index = 1:numel(result.temporary_files_remaining)
    lines{end + 1} = sprintf('[TEMPORARY FILE REMAINING] %s', ...
        result.temporary_files_remaining{index}); %#ok<AGROW>
end

for index = 1:numel(project.instances)
    instance = project.instances(index);
    if ~strcmp(instance.algorithm.mode, 'external_reference')
        continue;
    end
    source = c2837x_block_normalize_absolute_path( ...
        instance.algorithm.source_path);
    lines = [lines, {'External Reference:', ...
        sprintf('Instance: %s', instance.internal_name), ...
        sprintf('Source: %s', source), ...
        'Generated algorithm source: No', ...
        'Required action: Add the original .c source to the CCS project.'}]; %#ok<AGROW>
end

for index = 1:numel(legacyFileRisks)
    risk = legacyFileRisks(index);
    lines{end + 1} = sprintf(['Legacy File Risk: %s %s - %s ' ...
        'Old files are not automatically deleted by this generation.'], ...
        risk.action, risk.internal_name, risk.reason); %#ok<AGROW>
end
end
