    '                @MACRO@_PC_ERROR_HAS_ACTUAL_TYPE |\n' ...
    '                @MACRO@_PC_ERROR_HAS_EXPECTED_LENGTH |\n' ...
    '                @MACRO@_PC_ERROR_HAS_ACTUAL_LENGTH;\n' ...
    '            error->expected_type = @MACRO@_TYPE_OUTPUT_DATA;\n' ...
    '            error->actual_type = @MACRO@_TYPE_OUTPUT_DATA;\n' ...
    '            error->expected_length = @MACRO@_SFUN_OUTPUT_PAYLOAD_OCTETS;\n' ...
    '            error->actual_length = @MACRO@_SFUN_OUTPUT_PAYLOAD_OCTETS;\n' ...
    '            return -1;\n' ...
    '        }\n' ...
    '    }\n@COMMIT@' ...
    '    return 0;\n}\n']);
