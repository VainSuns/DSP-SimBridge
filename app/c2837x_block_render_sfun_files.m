function text = endian_helpers(layout)
inputSizes = [layout.input_fields.element_octets];
outputSizes = [layout.output_fields.element_octets];
text = '';
for octets = [2 4 8]
    if octets == 4 || any(inputSizes == octets)
        text = [text write_helper(octets)]; %#ok<AGROW>
    end
    if octets == 4 || any(outputSizes == octets)
        text = [text read_helper(octets)]; %#ok<AGROW>
    end
end
end

function text = write_helper(octets)
if octets == 2
    body = sprintf([ ...
        '    buffer[0] = (uint8_t)(value & 0xffu);\n' ...
        '    buffer[1] = (uint8_t)((value >> 8) & 0xffu);\n']);
elseif octets == 4
    body = sprintf([ ...
        '    buffer[0] = (uint8_t)(value & 0xffu);\n' ...
        '    buffer[1] = (uint8_t)((value >> 8) & 0xffu);\n' ...
        '    buffer[2] = (uint8_t)((value >> 16) & 0xffu);\n' ...
        '    buffer[3] = (uint8_t)((value >> 24) & 0xffu);\n']);
else
    body = sprintf([ ...
        '    unsigned int index;\n' ...
        '    for (index = 0u; index < 8u; ++index) {\n' ...
        '        buffer[index] = (uint8_t)((value >> (8u * index)) & 0xffu);\n' ...
        '    }\n']);
end
text = sprintf('static void @NAME@_sfun_write_le%u(uint8_t *buffer, uint%u_t value)\n{\n%s}\n\n', ...
    8 * octets, 8 * octets, body);
end

function text = read_helper(octets)
if octets == 2
    body = '    return (uint16_t)((uint16_t)buffer[0] | ((uint16_t)buffer[1] << 8));';
elseif octets == 4
    body = sprintf([ ...
        '    return (uint32_t)buffer[0] | ((uint32_t)buffer[1] << 8) |\n' ...
        '        ((uint32_t)buffer[2] << 16) | ((uint32_t)buffer[3] << 24);']);
else
    body = sprintf([ ...
        '    uint64_t value = 0u;\n' ...
        '    unsigned int index;\n' ...
        '    for (index = 0u; index < 8u; ++index) {\n' ...
        '        value |= (uint64_t)buffer[index] << (8u * index);\n' ...
        '    }\n' ...
        '    return value;']);
end
text = sprintf('static uint%u_t @NAME@_sfun_read_le%u(const uint8_t *buffer)\n{\n%s\n}\n\n', ...
    8 * octets, 8 * octets, body);
end

function text = pack_lines(variables, fields)
text = '';
for index = 1:numel(variables)
    port = index - 1;
    type = char(variables(index).type);
    bits = unsigned_type(fields(index).element_octets);
    writer = sprintf('sfun_write_le%u', 8 * fields(index).element_octets);
    text = [text sprintf([ ...
        '    {\n' ...
        '        const %s *values = (const %s *)signals[%u];\n' ...
        '        unsigned int element;\n' ...
        '        for (element = 0u; element < %u; ++element) {\n' ...
        '            %s bits;\n' ...
        '            memcpy(&bits, &values[element], sizeof(bits));\n' ...
        '            %s_%s(payload + %u + element * %u, bits);\n' ...
        '        }\n' ...
        '    }\n'], c_type(type), c_type(type), port, fields(index).dim, ...
        bits, '@NAME@', writer, 4 + fields(index).offset_octets, ...
        fields(index).element_octets)]; %#ok<AGROW>
end
end

function text = decode_lines(variables, fields)
text = '';
for index = 1:numel(variables)
    port = index - 1;
    bits = unsigned_type(fields(index).element_octets);
    reader = sprintf('sfun_read_le%u', 8 * fields(index).element_octets);
    text = [text sprintf([ ...
        '    {\n' ...
        '        unsigned int element;\n' ...
        '        for (element = 0u; element < %u; ++element) {\n' ...
        '            %s bits = %s_%s(payload + %u + element * %u);\n' ...
        '            memcpy(&temporary->output_%u[element], &bits, sizeof(bits));\n' ...
        '        }\n' ...
        '    }\n'], fields(index).dim, bits, '@NAME@', reader, ...
        4 + fields(index).offset_octets, fields(index).element_octets, port)]; %#ok<AGROW>
end
end

function text = commit_lines(variables)
text = '';
for index = 1:numel(variables)
    port = index - 1;
    text = [text sprintf( ...
        '    memcpy(signals[%u], temporary->output_%u, sizeof(temporary->output_%u));\n', ...
        port, port, port)]; %#ok<AGROW>
end
end

function value = unsigned_type(octets)
value = sprintf('uint%u_t', 8 * octets);
end

function value = c_type(type)
switch char(type)
    case 'int16', value = 'int16_t';
    case 'uint16', value = 'uint16_t';
    case 'int32', value = 'int32_t';
    case 'uint32', value = 'uint32_t';
    case 'single', value = 'float';
    case 'double', value = 'double';
    otherwise
        error('C2837xBlock:SfunRender:UnsupportedType', ...
            'Unsupported S-Function port type "%s".', char(type));
end
end

