function rendered = c2837x_block_render_dsp_instance_config_files(project)
%C2837X_BLOCK_RENDER_DSP_INSTANCE_CONFIG_FILES Render instance Config files.

c2837x_block_validate_project_structure(project);
layout = c2837x_block_build_dsp_wire_layout(project);
prototype = struct('instance_index', 0, 'internal_name', '', ...
    'config_header_bytes', zeros(1, 0, 'uint8'), ...
    'user_config_header_bytes', zeros(1, 0, 'uint8'), ...
    'config_source_bytes', zeros(1, 0, 'uint8'));
rendered = repmat(prototype, 1, numel(project.instances));
for index = 1:numel(project.instances)
    names = c2837x_block_build_instance_c_names( ...
        project.instances(index).internal_name);
    name = names.internal_name;
    macro = names.macro_prefix;
    typed = names.typed_prefix;
    [~, interfaceHash] = ...
        c2837x_block_build_interface_hash(project, index);
    definition = resolve_definition(project.instances(index).iodevice.type);
    support = validated_support(definition, project, index);
    rendered(index) = struct('instance_index', index, ...
        'internal_name', name, ...
        'config_header_bytes', text_bytes(config_header(project, ...
        name, macro, interfaceHash, layout.instances(index), support)), ...
        'user_config_header_bytes', text_bytes(user_header(macro)), ...
        'config_source_bytes', text_bytes(config_source(name, macro, typed, support)));
end
end

