function definition = resolve_definition(type)
[definition, found] = c2837x_block_get_iodevice_definition(type);
if ~found
    error('C2837xBlock:IoDevice:Unsupported', ...
        'Cannot render unsupported IoDevice type "%s".', char(type));
end
end

function support = validated_support(definition, project, index)
support = definition.render_instance_config_support(project, index);
second = definition.render_instance_config_support(project, index);
fields = {'header_definitions', 'header_checks', 'source_includes', ...
    'source_declarations', 'iodevice_ops_expression', ...
    'iodevice_channel_expression'};
valid = isstruct(support) && isscalar(support) && all(isfield(support, fields)) && ...
    all(cellfun(@(field) ischar(support.(field)) && isrow(support.(field)), ...
    fields([1 2 4 5 6]))) && iscell(support.source_includes) && ...
    isrow(support.source_includes) && ...
    all(cellfun(@(value) ischar(value) && isrow(value) && ~isempty(value), ...
    support.source_includes)) && numel(unique(support.source_includes)) == ...
    numel(support.source_includes) && ...
    ~isempty(support.iodevice_ops_expression) && ...
    ~isempty(support.iodevice_channel_expression) && isequal(support, second);
if ~valid
    error('C2837xBlock:IoDevice:InvalidInstanceConfigSupport', ...
        'IoDevice definition "%s" returned invalid instance Config support.', ...
        definition.type);
end
end

function bytes = text_bytes(text)
text = strrep(text, [char(13) newline], newline);
text = strrep(text, char(13), newline);
while ~isempty(text) && text(end) == newline
    text(end) = [];
end
bytes = reshape(uint8(unicode2native([text newline], 'UTF-8')), 1, []);
end
