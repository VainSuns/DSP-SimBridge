    unicode2native(sprintf([ ...
    '#define CONNECT_TIMEOUT_MS 500u\n' ...
    '#define STEP_TIMEOUT_MS 100u\n' ...
    '#define TERMINATE_TIMEOUT_MS 50u\n']), 'UTF-8'));
write_bytes(fullfile(generated, 'axis_alpha_protocol.c'), ...
    pc.protocol_source_bytes);
write_bytes(fullfile(generated, 'axis_alpha_protocol.h'), ...
    pc.protocol_header_bytes);
    write_bytes(fullfile(generated, 'axis_alpha_pc_error.h'), ...
        pc.pc_error_header_bytes);
    write_bytes(fullfile(generated, 'axis_alpha_pc_serial.h'), ...
        pc.serial_header_bytes);
support = fullfile(repositoryRoot, 'tests', 'app', 'support', 'sci_host');
gcc = 'E:\\Mingw_w64\\mingw64\\bin\\gcc.exe';
testCase.assertTrue(isfile(gcc), 'The configured MinGW gcc is required.');
executable = fullfile(root, 'sci_sfun_host_fixture.exe');
fixture = fullfile(support, 'sci_sfun_host_fixture.c');
serial = fullfile(support, 'sci_sfun_host_serial.c');
command = sprintf([ ...
    '"%s" -std=c11 -Wall -Wextra -Werror -pedantic-errors ' ...
    '-DMATLAB_MEX_FILE -I"%s" -I"%s" -I"%s" ' ...
    '"%s" "%s" -o "%s" 2>&1'], gcc, generated, ...
    fullfile(repositoryRoot, 'simulink'), support, fixture, serial, ...
    executable);
[status, compileOutput] = system(command);
testCase.assertEqual(status, 0, compileOutput);
[status, output] = system(sprintf('"%s" 2>&1', executable));
testCase.verifyEqual(status, 0, output);
end

function evidence = run_sci_production_binding(testCase)
root = c2837x_block_normalize_absolute_path(tempname);
mkdir(root);
testCase.addTeardown(@() rmdir(root, 's'));
sci = render_instance('sci');
generated = fullfile(root, 'generated');
mkdir(generated);
protocolSource = fullfile(generated, 'axis_alpha_protocol.c');
protocolHeader = fullfile(generated, 'axis_alpha_protocol.h');
serialSource = fullfile(generated, 'axis_alpha_pc_serial.c');
serialHeader = fullfile(generated, 'axis_alpha_pc_serial.h');
pcError = fullfile(generated, 'axis_alpha_pc_error.h');
write_bytes(protocolSource, unicode2native(sci.protocol, 'UTF-8'));
write_bytes(protocolHeader, unicode2native(sci.protocolHeader, 'UTF-8'));
write_bytes(serialSource, unicode2native(sci.serialSource, 'UTF-8'));
write_bytes(serialHeader, unicode2native(sci.serialHeader, 'UTF-8'));
write_bytes(pcError, unicode2native(sci.pcError, 'UTF-8'));

gcc = 'E:\\Mingw_w64\\mingw64\\bin\\gcc.exe';
testCase.assertTrue(isfile(gcc), 'The configured MinGW gcc is required.');
protocolObject = fullfile(root, 'axis_alpha_protocol.o');
serialObject = fullfile(root, 'c2837x_block_pc_serial.o');
common = sprintf([ ...
    '"%s" -std=c11 -Wall -Wextra -Werror -Wno-unused-function ' ...
    '-pedantic-errors -DC2837X_PC_SERIAL_TEST_SEAM ' ...
    '-I"%s" -c'], gcc, generated);
protocolCommand = sprintf('%s "%s" -o "%s" 2>&1', common, ...
    protocolSource, protocolObject);
serialCommand = sprintf('%s "%s" -o "%s" 2>&1', common, ...
    serialSource, serialObject);
[protocolStatus, protocolOutput] = system(protocolCommand);
[serialStatus, serialOutput] = system(serialCommand);
evidence = struct( ...
    'protocol_status', protocolStatus, ...
    'serial_status', serialStatus, ...
    'output', sprintf([ ...
    'PROTOCOL_COMMAND: %s\n%s\nSERIAL_COMMAND: %s\n%s\n' ...
    'GENERATED_SERIAL_HEADER: %s\nGENERATED_PC_ERROR: %s'], ...
    protocolCommand, protocolOutput, serialCommand, serialOutput, ...
    serialHeader, pcError));
end

function write_bytes(path, bytes)
file = fopen(path, 'wb');
assert(file >= 0);
cleanup = onCleanup(@() fclose(file));
fwrite(file, bytes, 'uint8');
clear cleanup
end

function value = section(text, startToken, endToken)
startPosition = strfind(text, startToken);
endPosition = strfind(text, endToken);
assert(isscalar(startPosition) && isscalar(endPosition) && ...
    startPosition < endPosition);
value = text(startPosition:endPosition - 1);
end

function verify_order(testCase, text, tokens)
positions = cellfun(@(token) strfind(text, token), tokens, ...
    'UniformOutput', false);
testCase.verifyTrue(all(cellfun(@(position) isscalar(position), positions)));
testCase.verifyTrue(issorted(cell2mat(positions)));
end
