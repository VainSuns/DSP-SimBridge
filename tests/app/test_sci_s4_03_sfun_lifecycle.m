    methods (Test)
        function testParameterContractAndGeneratedConfig(testCase)
            w5300 = render_instance('w5300_tcp');
            sci = render_instance('sci');
            userConfig = native2unicode( ...
                c2837x_block_render_sfun_build_files(sci.project).user_config_bytes, ...
                'UTF-8');

            testCase.verifySubstring(w5300.sfun, ...
                'ssSetNumSFcnParams(S, 0);');
            testCase.verifyEmpty(strfind(w5300.sfun, ...
                'ssSetSFcnParamTunable'));
            testCase.verifySubstring(w5300.config, ...
                '#define AXIS_ALPHA_SFUN_TCP_PORT 5000u');
            testCase.verifyEmpty(strfind(w5300.config, ...
                'SFUN_REQUESTED_BAUD'));

            testCase.verifySubstring(sci.sfun, ...
                'ssSetNumSFcnParams(S, 1);');
            testCase.verifySubstring(sci.sfun, ...
                'ssSetSFcnParamTunable(S, 0, 0);');
            testCase.verifySubstring(sci.sfun, ...
                '#define MDL_CHECK_PARAMETERS');
            testCase.verifySubstring(sci.sfun, ...
                'c2837x_pc_serial_configure(&context->serial,');
            testCase.verifySubstring(sci.sfun, ...
                'AXIS_ALPHA_SFUN_REQUESTED_BAUD');
            testCase.verifySubstring(sci.config, ...
                '#define AXIS_ALPHA_SFUN_IODEVICE_SCI 1u');
            testCase.verifySubstring(sci.config, ...
                '#define AXIS_ALPHA_SFUN_REQUESTED_BAUD 57600u');
            testCase.verifySubstring(sci.config, ...
                '#define AXIS_ALPHA_SFUN_NOMINAL_BAUD 57600u');
            testCase.verifyFalse(contains(sci.config, 'COM'));
            testCase.verifyFalse(contains(sci.config, 'DSP_IP_ADDRESS'));
            testCase.verifyFalse(contains(sci.config, 'TCP_PORT'));

            testCase.verifyEqual( ...
                numel(regexp(userConfig, '(?m)^#define\s+', 'match')), 4);
            testCase.verifySubstring(userConfig, ...
                '#define CONNECT_TIMEOUT_MS');
            testCase.verifySubstring(userConfig, ...
                '#define STEP_TIMEOUT_MS');
            testCase.verifySubstring(userConfig, ...
                '#define TERMINATE_TIMEOUT_MS');
            testCase.verifyEmpty(regexpi(userConfig, ...
                'SERIAL_TIMEOUT|SERIAL_OPEN_TIMEOUT|SERIAL_RX_TIMEOUT|SERIAL_TX_TIMEOUT', ...
                'once'));
        end

