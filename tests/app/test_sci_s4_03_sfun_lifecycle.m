        function testSciStartStepTerminateLifecycle(testCase)
            sci = render_instance('sci');
            start = section(sci.sfun, 'static void mdlStart', ...
                'static void mdlOutputs');
            step = section(sci.sfun, 'static void mdlOutputs', ...
                'static void mdlTerminate');
            terminate = section(sci.sfun, 'static void mdlTerminate', ...
                '#ifndef MATLAB_MEX_FILE');
            destroy = section(sci.sfun, ...
                'void axis_alpha_sfun_destroy_context', ...
                'static const char *axis_alpha_sfun_error_text(SimStruct *S,');

            verify_order(testCase, start, { ...
                'axis_alpha_sfun_parse_com_number', ...
                'axis_alpha_sfun_create_context', ...
                'c2837x_pc_serial_init', ...
                'c2837x_pc_serial_open', ...
                'c2837x_pc_serial_configure', ...
                'c2837x_pc_serial_purge', ...
                'axis_alpha_protocol_send_sim_start', ...
                'axis_alpha_protocol_wait_response', ...
                'context->step_index = 0u', ...
                'context->session_started = 1'});
            testCase.verifyEqual(numel(strfind(start, ...
                'c2837x_pc_serial_purge')), 1);
            testCase.verifyEqual(numel(strfind(start, ...
                'STEP_TIMEOUT_MS')), 2);
            testCase.verifyEmpty(strfind(start, 'CONNECT_TIMEOUT_MS'));
            testCase.verifyEmpty(regexpi(start, ...
                'sleep|retry|reconnect|autobaud|bootloader|CreateFile|''A''', 'once'));
            testCase.verifySubstring(start, ...
                'ssSetPWorkValue(S, 0, NULL);');
            testCase.verifySubstring(start, ...
                'axis_alpha_sfun_destroy_context(context);');

            verify_order(testCase, step, { ...
                'axis_alpha_sfun_pack_input_payload', ...
                'axis_alpha_protocol_send_input_data', ...
                'axis_alpha_protocol_wait_output_data', ...
                'axis_alpha_sfun_decode_output_payload', ...
                'axis_alpha_sfun_commit_output_ports', ...
                'context->step_index++'});
            testCase.verifyEqual(numel(strfind(step, ...
                'STEP_TIMEOUT_MS')), 2);
            testCase.verifySubstring(sci.sfun, 'c2837x_pc_serial_close');
            testCase.verifySubstring(sci.sfun, 'context->session_started = 0;');
            testCase.verifySubstring(sci.sfun, 'ssSetErrorStatus(S,');
            testCase.verifyEmpty(regexpi(step, ...
                'retry|reconnect|resend|pipeline|thread|CreateFile|Sleep', 'once'));

            verify_order(testCase, terminate, { ...
                'axis_alpha_protocol_send_sim_stop', ...
                'axis_alpha_sfun_destroy_context'});
            testCase.verifySubstring(terminate, ...
                ['axis_alpha_sfun_destroy_context(context);' newline ...
                 '    ssSetPWorkValue(S, 0, NULL);']);
            testCase.verifyEqual(numel(strfind(terminate, ...
                'TERMINATE_TIMEOUT_MS')), 1);
            testCase.verifySubstring(terminate, 'cleanup_error');
            testCase.verifyEmpty(strfind(terminate, ...
                'axis_alpha_protocol_wait_response'));
            testCase.verifyEmpty(strfind(terminate, 'ssSetErrorStatus'));
            verify_order(testCase, destroy, { ...
                'c2837x_pc_serial_close', 'free(context)'});
        end

        function testSingleProtocolBindingUsesOneReceiveDeadline(testCase)
            w5300 = render_instance('w5300_tcp');
            sci = render_instance('sci');
            receive = section(sci.protocol, ...
                'int axis_alpha_protocol_recv_frame', ...
                'int axis_alpha_protocol_send_sim_start');
            send = section(sci.protocol, ...
                'static int axis_alpha_protocol_send_complete_frame', ...
                'int axis_alpha_protocol_recv_frame');

            testCase.verifySubstring(w5300.protocol, ...
                'axis_alpha_protocol_send_input_data(AxisAlphaPcSocket *socket,');
            testCase.verifyEmpty(regexpi(sci.protocol, ...
                'protocol_tcp|protocol_sci', 'once'));
            testCase.verifySubstring(sci.protocolHeader, ...
                '#include "axis_alpha_pc_serial.h"');
            testCase.verifyEmpty(strfind(sci.protocolHeader, ...
                'c2837x_block_pc_serial.h'));
            testCase.verifySubstring(sci.protocol, ...
                'c2837x_pc_serial_deadline_start');
            testCase.verifySubstring(sci.protocol, ...
                'c2837x_pc_serial_send_all_until');
            testCase.verifySubstring(sci.protocol, ...
                'c2837x_pc_serial_recv_exact_until');
            testCase.verifyEqual(numel(strfind(sci.protocol, ...
                'c2837x_pc_serial_recv_exact(')), 0);
            verify_order(testCase, receive, { ...
                'axis_alpha_pc_serial_deadline_start', ...
                'axis_alpha_pc_serial_recv_exact_until(socket, header', ...
                'axis_alpha_pc_serial_recv_exact_until(socket, payload'});
            verify_order(testCase, send, { ...
                'axis_alpha_pc_serial_deadline_start', ...
                'axis_alpha_pc_serial_send_all_until'});
            testCase.verifyEqual(numel(strfind(receive, '&deadline')), 3);
            testCase.verifyEqual(numel(strfind(send, '&deadline')), 2);
        end

