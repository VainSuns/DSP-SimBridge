function definition = c2837x_block_iodevice_test_provider_definition()
% Test-only IoDevice definition with settings unrelated to W5300.

definition = struct('type', 'test_provider', 'max_instance_count', Inf, ...
    'validate_settings', @validate_settings, ...
    'collect_resource_claims', @collect_resource_claims, ...
    'render_project_support', @render_project_support, ...
    'render_instance_config_support', @render_instance_config_support, ...
    'render_instance_io_support', @render_instance_io_support);
end

function support = render_instance_io_support(project, instanceIndex)
name = char(project.instances(instanceIndex).internal_name);
support = struct('source_includes', {{'test_provider_channel.h'}}, ...
    'source_definitions', sprintf( ...
    'TestProviderChannel c2837x_block_%s_iodevice_channel = {0};\n', name));
end

function support = render_instance_config_support(project, instanceIndex)
name = char(project.instances(instanceIndex).internal_name);
macro = upper(name);
channel = project.instances(instanceIndex).iodevice.settings.channel_id;
support = struct( ...
    'header_definitions', sprintf( ...
    '#define %s_TEST_CHANNEL_ID  %uu\n', macro, channel), ...
    'header_checks', sprintf( ...
    '%s_STATIC_ASSERT(%s_TEST_CHANNEL_ID == 42u, test_channel_invalid);\n', ...
    macro, macro), ...
    'source_includes', {{'test_provider_channel.h'}}, ...
    'source_declarations', sprintf( ...
    'extern TestProviderChannel c2837x_block_%s_iodevice_channel;\n', name), ...
    'iodevice_ops_expression', '&test_provider_iodevice_ops', ...
    'iodevice_channel_expression', ...
    ['&c2837x_block_' name '_iodevice_channel']);
end

function issues = validate_settings(settings, instanceIndex)
issues = struct('severity', {}, 'code', {}, 'message', {}, ...
    'field_path', {}, 'instance_index', {}, 'file_path', {});
if ~isfield(settings, 'channel_id') || settings.channel_id ~= 42
    issues(1) = struct('severity', 'Error', 'code', 'TEST_CHANNEL_INVALID', ...
        'message', 'Test provider validation was called.', ...
        'field_path', sprintf( ...
        'project.instances(%u).iodevice.settings.channel_id', instanceIndex), ...
        'instance_index', instanceIndex, 'file_path', '');
end
end

function claims = collect_resource_claims(~, ~)
claims = struct('scope', {}, 'kind', {}, 'key', {}, 'exclusive', {}, ...
    'duplicate_code', {}, 'duplicate_message', {}, 'field_path', {}, ...
    'instance_index', {});
end

function support = render_project_support(~)
support = struct('includes', {{}}, ...
    'source', sprintf('/* test provider project support */\n'));
end
