classdef test_s3_04_w5300_udp_lifecycle < matlab.unittest.TestCase
    methods (Test)
        function testUdpSessionCleanupAndReacquisition(testCase)
            [status, output] = test_s3_04_w5300_udp_lifecycle.compileAndRun();
            testCase.verifyEqual(status, 0, output);
