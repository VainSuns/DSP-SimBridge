function testInternalContractContainsFrozenBindings(testCase)
root = repository_root();
header = fileread(fullfile(root, 'dsp', 'src', ...
    'c2837x_block_config_internal.h'));
for field = {'iodevice_ops', 'iodevice_channel', ...
        'rx_frame_words', 'rx_frame_capacity_octets', ...
        'tx_frame_words', 'tx_frame_capacity_octets', ...
        'input_object', 'output_object', 'algorithm', ...
        'algorithm_context', 'protocol_version', 'interface_hash', ...
        'input_payload_octets', 'output_payload_octets', ...
        'max_payload_octets', 'interaction_timeout_us', ...
        'transfer_timeout_us'}
    verifyNotEmpty(testCase, regexp(header, ['\<' field{1} '\>'], 'once'), ...
        field{1});
end
for callback = {'reset_io', 'on_start', 'decode_input', ...
        'on_step', 'encode_output', 'on_stop'}
    verifyNotEmpty(testCase, regexp(header, ['\<' callback{1} '\>'], 'once'), ...
        callback{1});
end
end

function testBindingStaysInternalAndUnique(testCase)
root = repository_root();
publicHeader = fileread(fullfile(root, 'dsp', 'inc', 'c2837x_block.h'));
internalHeader = fileread(fullfile(root, 'dsp', 'src', ...
    'c2837x_block_internal.h'));
sources = read_tree(fullfile(root, 'dsp'));
verifyEmpty(testCase, regexp(publicHeader, ...
    'Config|AlgorithmAdapter|IoDevice|void\s*\*', 'once'));
verifyNotEmpty(testCase, regexp(internalHeader, ...
    'C2837X_BLOCK_INSTANCE_INITIALIZER', 'once'));
verifyEmpty(testCase, regexp(sources, ...
    ['c2837x_block_' 'bind_iodevice'], 'once'));
verifyEmpty(testCase, regexp(sources, ...
    '\<(bind_config|register_device|set_callbacks)\s*\(', 'once'));
end

