function text = read_tree(folder)
files = [dir(fullfile(folder, '**', '*.c')); ...
         dir(fullfile(folder, '**', '*.h'))];
text = '';
for index = 1:numel(files)
    text = [text newline fileread(fullfile(files(index).folder, ...
        files(index).name))]; %#ok<AGROW>
end
end

